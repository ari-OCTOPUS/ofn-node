def seed_edge_model(store) -> int:
    """چانک‌های مدل لبه را به دیتابیس اضافه کن. idempotent.

    اگر چانکی با همان source_url و section از قبل باشد، رد می‌شود.
    خروجی: تعداد چانک‌های تازه‌اضافه‌شده.
    """
    n = 0
    for ch in CHUNKS:
        title = f"{EDGE_TITLE_PREFIX} — {ch['section']}"
        # idempotency: اگر این section از قبل ingest شده، رد کن
        with store.conn() as db:
            exists = db.execute(
                "SELECT 1 FROM research_docs WHERE source_url=? AND title=? LIMIT 1",
                (EDGE_SOURCE_URL, title),
            ).fetchone()
        if exists:
            continue
        text = "[category: math_models]\n[section: {}]\n[source: {}]\n\n{}".format(
            ch['section'], EDGE_SOURCE_URL, ch['text'].strip())
        store.add_research(title, text, EDGE_SOURCE_URL, 'edge_seed', ch['tags'])
        n += 1
    return n
