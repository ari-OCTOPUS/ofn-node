"""Write a Persian report strictly from the completed, checked study outputs."""
import argparse
import json
from pathlib import Path
import numpy as np


def table(headers, rows):
    return "\n".join(["| " + " | ".join(headers) + " |",
                      "| " + " | ".join(["---"] * len(headers)) + " |"] +
                     ["| " + " | ".join(map(str, row)) + " |" for row in rows])


def write_report(results):
    out = results / "analysis"
    s = json.loads((out / "summary.json").read_text(encoding="utf-8"))
    p = s["primary_run"]["final"]
    cfg = s["study"]["config"]
    history = json.loads((results / f"full_seed{s['primary_run']['seed']}" / "history.json").read_text(encoding="utf-8"))
    names = {"full": "MAP-Elites ترکیبی", "mutation": "MAP-Elites فقط جهش",
             "random": "تصادفی + آرشیو", "crossover": "ترکیب یکنواخت + جهش"}
    agg_rows = []
    for mode, group in s["aggregate"].items():
        m = group["metrics"]
        agg_rows.append([names[mode], group["n"], f"{m['coverage']['mean']*100:.2f}%",
                         f"{m['center_free_coverage']['mean']*100:.2f}%",
                         f"{m['qd_score']['mean']:.2f}", f"{m['mean_fitness']['mean']:.4f}",
                         f"{m['coverage']['min']*100:.2f} تا {m['coverage']['max']*100:.2f}%"])
    run_rows = [[names[r["mode"]], r["seed"], r["final"]["evals"], r["final"]["n_elites"],
                 f"{r['final']['coverage']*100:.2f}%", f"{r['final']['qd_score']:.2f}"]
                for r in s["runs"]]
    curve_rows = [[r["gen"], r["evals"], r["n_elites"], f"{r['coverage']*100:.2f}%",
                   f"{r['qd_score']:.2f}", f"{r['mean_fitness']:.4f}"]
                  for r in history if r["gen"] % 100 == 0 or r["gen"] == cfg["generations"]]
    op_rows = [[name, r["attempts"], r["admitted"], r["survived_batch"], r["new_cells"],
                f"{100*r['admitted']/r['attempts']:.2f}%"]
               for name, r in s["operators"].items() if r["attempts"]]
    room_rows = [[name, r["elites"], f"{r['mean_fitness']:.4f}" if r["mean_fitness"] is not None else "UNKNOWN",
                  r["median_first_discovery"], r["median_last_replacement"]]
                 for name, r in s["rooms"].items()]
    g = s["genetics"]
    layer_rows = [[name, f"{r['mean']:.4f}", f"{r['std']:.4f}",
                   f"{r['min']:.4f}", f"{r['max']:.4f}"] for name, r in g["layer_stats"].items()]
    card = s["elite_cards"][0]
    card_rows = [[c["id"], c["operator"], c["parents"], f"{c['fitness']:.4f}",
                  f"({c['descriptor'][0]:.4f}, {c['descriptor'][1]:.4f})",
                  f"{c['episode']['path_len']:.4f}"] for c in s["elite_cards"]]
    matrices = "\n\n".join(f"{name} =\n{np.array2string(np.array(card[name]), precision=4, suppress_small=True)}"
                            for name in ("W1", "b1", "W2", "b2"))
    hrows = []
    for h in s["hypotheses"]:
        delta = h.get("measured_delta")
        measured = (f"Δپوشش = {delta['mean_coverage_delta']*100:+.2f} واحد درصد؛ "
                    f"ΔQD نسبی = {delta['mean_qd_relative_delta']*100:+.2f}%") if delta else "آزمون‌های محلی و بررسی رسیدها"
