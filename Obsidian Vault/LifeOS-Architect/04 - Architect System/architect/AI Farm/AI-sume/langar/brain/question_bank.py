LABELS = {
    "body_hrv": "بدن / HRV", "mind_emotion": "ذهن / هیجان",
    "relationships": "رابطه‌ها / ارتباط", "work_engineering": "کار / مهندسی",
    "meaning_direction": "معنا / جهت", "habits_environment": "عادت‌ها / محیط",
}


class QuestionBank:
    def label(self, domain: str) -> str:
        return LABELS.get(domain, domain)

    def get_question(self, domain: str, context: dict | None = None) -> str:
        bank = BANK.get(domain) or BANK["body_hrv"]
        # چرخش بر اساسِ روزِ سال + تعدادِ بازتاب‌ها (اگر در context باشد)
        seed = _dt.date.today().toordinal() + int((context or {}).get("rotation", 0))
        q = bank[seed % len(bank)]
        why = (context or {}).get("why") or "امروز نوبتِ این حوزه است تا کارگاه یک‌بُعدی نشود."
        return f"🧭 حوزه: {self.label(domain)}\n❓ {q}\nچرا امروز: {why}"
