"""
optimizer.py — ایجنت Optimizer: پیشنهادِ نسخه‌ی بهترِ system prompt.

دو نوع پیشنهاد:
  - propose_fix: یک معیارِ جاافتاده‌ی rubric را با افزودن یک دستور برطرف می‌کند (بهبود).
  - propose_explore: یک بازنویسیِ آزمایشی که عمداً ممکن است بدتر شود
    (برای نشان‌دادنِ سازوکارِ rollback: حتی اعمالِ خودکار هم نمی‌تواند سیستم را بدتر کند).

پیشنهادها قطعی‌اند تا حلقه آفلاین و تکرارپذیر بماند. در حالت LIVE می‌توان
به‌جای این، از خودِ Claude برای بازنویسیِ پرامپت استفاده کرد (همان رابط complete).
"""
from __future__ import annotations

SUGGESTIONS: dict[str, dict[str, str]] = {
    "researcher": {
        "ذکر منبع": "برای هر ادعا منبع آن را ذکر کن.",
        "پرچم عدم‌قطعیت": "هر ادعای نامطمئن را صریح برای راستی‌آزمایی پرچم بزن.",
        "ماندن در نقش": "خودت تحلیل یا نتیجه‌گیری نهایی نکن.",
        "ساختار منظم": "یافته‌ها را در چند بندِ منظم ارائه کن.",
        "اختصار": "گزارش را کوتاه و مختصر نگه دار.",
    },
    "analyst": {
        "پرچم عدم‌قطعیت": "ادعاهای نامطمئن را برای راستی‌آزمایی علامت بزن.",
        "نساختنِ منبع جدید": "حق جستجوی جدید نداری؛ فقط بر اساس یافته‌های داده‌شده کار کن.",
        "صداقت": "تحلیل باید صادقانه و دقیق باشد.",
        "اختصار": "خلاصه را کوتاه نگه دار.",
    },
    "supervisor": {
        "تصمیم صریح": "پاسخت را با APPROVE یا REJECT شروع کن.",
        "دلیل": "برای رد، دلیل کوتاه بنویس.",
        "ماندن در نقش": "خودت محتوای جدید تولید نکن.",
    },
}


class Optimizer:
    name = "optimizer"

    def __init__(self, llm=None):
        self.llm = llm  # در حالت LIVE می‌توان برای بازنویسی استفاده کرد

    def propose_fix(self, agent: str, prompt: str, missing: list[str]) -> str:
        """اولین معیارِ جاافتاده را با افزودن یک دستور برطرف می‌کند."""
        target = missing[0]
        instruction = SUGGESTIONS.get(agent, {}).get(target, "")
        if not instruction:
            return prompt
        return (prompt.rstrip() + " " + instruction).strip()

    def propose_explore(self, agent: str, prompt: str) -> str:
        """
        بازنویسیِ آزمایشی: عمداً معیارِ «اختصار» را حذف می‌کند تا نشان دهیم
        اگر یک تغییر نمره را پایین بیاورد، سیستم خودکار rollback می‌کند.
        """
        p = prompt.replace("کوتاه و مختصر", "جامع و مفصل")
        p = p.replace("کوتاه", "مفصل").replace("مختصر", "کامل")
        return (p + " توضیحات را تا حد امکان طولانی و کامل بنویس.").strip()
