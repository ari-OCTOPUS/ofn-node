#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""leg_commands — ۹ فرمانِ طبیعیِ نسخهٔ اولِ اتاقِ کنترل (رأیِ مالک ۲۰۲۶-۰۷-۳۱).

    وضعیت · صف · ادامه بده · متوقف شو · قدم بعدی · مانع چیست ·
    شاهد بده · گزارش امروز · این را به صف اضافه کن

چرا این ماژول لازم شد: مدلِ Task می‌گوید «هر پیامِ غیرسؤال = یک کار». ولی
مالک در تاپیکِ پا «وضعیت» می‌نویسد و انتظارِ **جواب** دارد، نه اینکه یک
TASK با متنِ «وضعیت» صف شود. پس قبل از intake، فرمانِ طبیعی جدا می‌شود.

مرزها:
  · تابعِ خالص، stdlib، صفر I/O، صفر ارسال — همان قراردادِ input_surface_policy.
  · تشخیص فقط با **تطابقِ کاملِ** متنِ نرمال‌شده روی یک مجموعهٔ بسته.
    درسِ بیش‌بست (LEG_ALIASES): «وضعیت سایتِ مشتری را بررسی کن» باید کار
    بماند؛ substring-match آن را می‌بلعید. فرمانِ تشخیص‌نشده هزینه‌اش صفر است
    (می‌شود Task و مالک لغوش می‌کند)؛ کارِ بلعیده‌شده بی‌صدا گم می‌شود.
  · اجرای فرمان با مرکز است (همان مسیرِ ممیزی‌شدهٔ دکمه‌ها) — این‌جا فقط نگاشت.
"""
from __future__ import annotations

import re

# کلیدهای فرمان — هر کلید باید در `Center._exec_leg_command` شاخه داشته باشد
# (تستِ ضدِ دکمهٔ مرده همین را قفل می‌کند).
COMMANDS = ("status", "queue", "resume", "pause", "next",
            "blockers", "receipts", "report")

# شکل‌های پذیرفته — عمداً کوتاه و بسته. شکلِ تازه فقط با رأیِ مالک اضافه
# می‌شود؛ حدسِ معنایی ممنوع (درسِ «مسیریابی به فلگِ خاموش»).
_FORMS = {
    "status":   ("وضعیت", "وضعیت این پا چیه", "وضعیت چیه", "status"),
    "queue":    ("صف", "صف کار", "صف را نشان بده", "صف رو نشون بده",
                 "نمایش صف"),
    "resume":   ("ادامه", "ادامه بده"),
    "pause":    ("توقف", "متوقف شو", "فعلا متوقف شو", "فعلاً متوقف شو"),
    "next":     ("قدم بعدی", "کار بعدی", "اجرای بعدی", "بعدی"),
    "blockers": ("مانع", "موانع", "مانع چیست", "مانع چیه", "چرا گیر کردی"),
    "receipts": ("شاهد", "شاهدها", "شاهد بده"),
    "report":   ("گزارش", "گزارش امروز", "گزارش روزانه"),
}

# «این را به صف اضافه کن …» — تنها فرمانی که دنباله دارد؛ دنباله همان کار است.
_ENQUEUE = re.compile(
    r"^(?:این\s+(?:را|رو)\s+)?(?:به\s+صف\s+اضافه\s+کن|اضافه\s+کن\s+به\s+صف)"
    r"[:،\s]*(.*)$", re.S)

_PUNCT = re.compile(r"[؟?!.…۔]+$")
_WS = re.compile(r"\s+")


def _norm(text: str) -> str:
    t = _WS.sub(" ", str(text or "").strip())
    t = _PUNCT.sub("", t).strip()
    return t.lower()


_LOOKUP = {}
for _cmd, _forms in _FORMS.items():
    for _f in _forms:
        _LOOKUP[_norm(_f)] = _cmd


def classify(text: str) -> "str | None":
    """متن → کلیدِ فرمان، یا None (⇒ مسیرِ عادی: سؤال/کار). فقط تطابقِ کامل."""
    return _LOOKUP.get(_norm(text))


def strip_enqueue_prefix(text: str) -> "str | None":
    """«این را به صف اضافه کن: X» → «X». بدونِ پیشوند → None.

    دنبالهٔ خالی → "" برمی‌گردد (نه None) تا مرکز بتواند از پیامِ ریپلای‌شده
    پرش کند یا صادقانه بپرسد «چه چیزی؟» — حدس نمی‌زنیم."""
    m = _ENQUEUE.match(_WS.sub(" ", str(text or "").strip()))
    if not m:
        return None
    return _PUNCT.sub("", m.group(1).strip()).strip()
