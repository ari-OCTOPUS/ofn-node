def _norm(text: str) -> str:
    """عربی/فارسی را یکدست کن و فاصله‌ها را جمع — وگرنه «می‌تونم» و «میتونم»
    دو چیز می‌شوند و جدولِ کلیدواژه بی‌صدا نصفه کار می‌کند."""
    t = str(text or "").lower()
    for a, b in (("ي", "ی"), ("ك", "ک"), ("ۀ", "ه"), ("ة", "ه"),
                 ("‌", " "), ("‌", " ")):
        t = t.replace(a, b)
    return re.sub(r"\s+", " ", t).strip()


def _of(key: str, reason: str, hits=None) -> dict:
    disp, cmd, _w = _table()[key]
    return {"match": key, "display": disp, "command": cmd,
            "hits": hits or [], "tied": [], "reason": reason}


def classify(text: str, room: str = "") -> dict:
    """کدام کارمند؟ خروجی همیشه توضیح‌پذیر است.

    {match: key|None, display, command, hits: [...], tied: [...], reason}
    `tied` غیرخالی یعنی مبهم بود — صداکننده باید **بپرسد**، نه انتخاب کند.

    `room` = تاپیکی که پیام در آن آمده (خالی = General/خصوصی). سه قاعده، به
    همین ترتیب — و ترتیبشان تمامِ ماجراست:

      ۱ کلیدواژهٔ صریح همیشه برنده است، حتی در اتاقِ دیگری. در تاپیکِ ماینینگ
        «پول چطوره» یعنی پول. چیزی که بلند گفته‌ای بر جایی که ایستاده‌ای مقدم
        است، وگرنه اتاق تبدیل به زندان می‌شود.
      ۲ ابهام + یکی از نامزدها همان اتاق → همان. این حدس نیست: اتاق یک
        contextِ **اعلام‌شده** است، نه استنباط.
      ۳ بی‌کلیدواژه + اتاقِ موضوع‌دار → موضوعِ اتاق. این همان چیزی است که گروه
        را از تابلوی اعلانات به پایگاه تبدیل می‌کند.

    `room=""` → رفتارِ قبلی، بایت‌به‌بایت.
    """
    subject = ROOM_SUBJECT.get(str(room or "").strip())
    t = _norm(text)
    if not t:
        # اتاق حتی به پیامِ خالی هم معنا می‌دهد، ولی چیزی برای گفتن نیست.
        return {"match": None, "hits": [], "tied": [], "reason": "empty"}
    table = _table()
    scores: dict[str, list] = {}
    spans: dict[str, list] = {}
    for key, (_disp, _cmd, words) in table.items():
        hit, sp = [], []
        for w in words:
            i = t.find(_norm(w))
            if i >= 0:
                hit.append(w)
                sp.append((i, i + len(_norm(w))))
        if hit:
            scores[key] = hit
            spans[key] = sp
    if not scores:
        # قاعدهٔ ۳ — پایگاه: اتاق موضوع دارد، پس جمله یتیم نیست.
        if subject in table:
            return _of(subject, "room-context")
        return {"match": None, "hits": [], "tied": [], "reason": "no-keyword"}

    # امتیاز = تعدادِ کلیدواژه؛ در تساوی، طولِ بلندترین تطابق.
    def _rank(k):
        return (len(scores[k]), max(len(w) for w in scores[k]))

    def _subsumed(rival: str, win: str) -> bool:
        """آیا اصابت‌های rival همان‌جایی‌اند که برنده گرفته؟

        فرقِ «پولِ ماینینگ» با «پول و ماینینگ» همین است. در اولی دو کلیدواژه
        روی یک ناحیه‌اند و خاص‌تر باید ببرد؛ در دومی مالک **دو موضوع** نام برده
        و انتخابِ یکی‌شان مسیریابیِ غلطِ بی‌صداست.

        نسخهٔ اولِ این تابع فقط طول را می‌سنجید و «پول و ماینینگ» را بی‌صدا به
        ماینینگ می‌داد — چون «ماینینگ» ۷ حرف است و «پول» ۳. تست گرفتش.
        """
        return all(any(a < we and ws < b for (ws, we) in spans[win])
                   for (a, b) in spans[rival])

    best = max(scores, key=_rank)
    tied = [k for k in scores
            if k != best and (_rank(k) == _rank(best) or not _subsumed(k, best))]
    disp, cmd, _ = table[best]
    if tied:
        # قاعدهٔ ۲ — اتاق تساوی را می‌شکند، ولی فقط اگر خودش یکی از نامزدها
        # باشد. اتاقی که ربطی به هیچ‌کدام ندارد حقِ رأی ندارد؛ آن‌جا پرسیدن
        # همچنان درست است.
        if subject in ([best] + tied):
            return _of(subject, "room-breaks-tie", scores.get(subject))
        return {"match": None, "hits": scores[best], "tied": [best] + tied,
                "reason": "ambiguous"}
    # نامِ خودِ اتاق را گفتن = ماندن در اتاق، نه جهش. «مغز چطوره» در اتاقِ مغز
    # یعنی همان اتاق؛ همان جمله در جای دیگر یعنی کورتکس.
    if subject in table and subject != best:
        _alias = ROOM_ALIAS.get(str(room or "").strip()) or ()
        if any(_norm(a) in t for a in _alias):
            return _of(subject, "room-alias", scores[best])
    # پرسشِ عمومیِ وضعیت در اتاقِ موضوع‌دار → وضعیتِ **همان** موضوع.
    if best in ROOM_OVERRIDES_STAFF and subject in table and subject != best:
        return _of(subject, "room-owns-status", scores[best])
    # قاعدهٔ ۱ — کلیدواژهٔ صریح، حتی در اتاقِ دیگری.
    return {"match": best, "display": disp, "command": cmd,
            "hits": scores[best], "tied": [], "reason": "keyword"}


def menu() -> str:
    """فهرستِ کوتاهِ کارمندها — فقط زنده‌ها، بدونِ فرمانِ خیالی."""
    lines = ["🏢 <b>با کی حرف بزنم؟</b>", ""]
    for _k, (disp, cmd, _w) in STAFF.items():
        lines.append(f"• {disp} — <code>{cmd}</code>")
    lines.append("")
    lines.append("<i>یا فقط فارسی بنویس: «چه خبر» · «پول چطوره» · "
                 "«مشکلی هست؟» · «چی یاد گرفتی»</i>")
    return "\n".join(lines)


def ask_which(tied: list) -> str:
    """کارتِ ابهام — می‌پرسد به‌جای حدس‌زدن."""
    table = {**STAFF, **LEGS}
    opts = " · ".join(f"{table[k][0]} <code>{table[k][1]}</code>"
                      for k in tied if k in table)
    return ("🤔 <b>دو جور می‌شود خواندش</b>\n"
            f"منظورت کدام بود؟ {opts}\n"
            "<i>مسیریابیِ غلطِ بی‌صدا بدتر از پرسیدن است — جوابِ کارمندِ اشتباه "
            "شبیهِ جوابِ درست به نظر می‌رسد.</i>")


def card() -> str:
    """کارتِ `/x`."""
    if not enabled():
        return ("🏢 <b>اتاقِ چت</b>\n"
                f"خاموش. روشن‌کردن: <code>OWNER_AUTH: ARM FLAG {FLAG}</code>\n"
                f"▸ {len(STAFF)} کارمندِ زنده + {len(LEGS)} پا، بدونِ حفظ‌کردنِ فرمان.")
    brain = "روشن" if str(os.environ.get(BRAIN_FLAG, "")).strip().lower() in (
        "1", "true", "yes", "on") else "خاموش"
    return ("🏢 <b>اتاقِ چت</b> · روشن\n"
            f"▸ {len(STAFF)} کارمند + {len(LEGS)} پا · لایهٔ مغزِ محلی: {brain}\n"
            "▸ مبهم = می‌پرسد، حدس نمی‌زند.")
